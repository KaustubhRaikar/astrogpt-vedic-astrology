def get_festival_for_date(date_str: str) -> dict | None:
    """Lookup curated festival information for a date formatted as YYYY-MM-DD.
    Returns dict or None if no festival is listed on that date."""
    return FESTIVAL_DATABASE.get(date_str)


def get_festivals_for_month(year: int, month: int) -> list[dict]:
    """Returns a list of all festivals falling in a given year and month."""
    prefix = f"{year:04d}-{month:02d}"
    results = []
    for date_str, item in FESTIVAL_DATABASE.items():
        if date_str.startswith(prefix):
            results.append({"date": date_str, **item})
    results.sort(key=lambda x: x["date"])
    return results
